import 'dart:typed_data';

import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:flutter_core/flutter_core.dart';
import 'package:printing/printing.dart';
import 'package:share_plus/share_plus.dart';

import 'qr_api.dart';
import 'qr_models.dart';

/// "QR code and poster": view the salon's permanent QR code, copy or share the link, share the image, and print / save / share
/// the PDF poster. The QR code never changes when the salon edits its details, so a printed poster stays valid.
class QrScreen extends StatefulWidget {
  const QrScreen({super.key, required this.api});

  final QrApi api;

  @override
  State<QrScreen> createState() => _QrScreenState();
}

class _QrScreenState extends State<QrScreen> {
  SalonQrInfo? _info;
  Uint8List? _png;
  ApiException? _error;
  bool _loading = true;
  bool _busy = false;
  String _size = 'A4';
  String _theme = 'light';

  @override
  void initState() {
    super.initState();
    _load();
  }

  Future<void> _load() async {
    setState(() {
      _loading = true;
      _error = null;
    });
    try {
      final info = await widget.api.info();
      final png = await widget.api.image(size: 1024);
      if (mounted) {
        setState(() {
          _info = info;
          _png = png;
        });
      }
    } on ApiException catch (e) {
      if (mounted) setState(() => _error = e);
    } finally {
      if (mounted) setState(() => _loading = false);
    }
  }

  void _toast(String message) => ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text(message)));

  Future<void> _copy(String link) async {
    await Clipboard.setData(ClipboardData(text: link));
    _toast('Link copied');
  }

  Future<void> _shareLink(SalonQrInfo info) async {
    await Share.share('Book your appointment at ${info.salonName}: ${info.link}');
  }

  Future<void> _shareImage(SalonQrInfo info, Uint8List png) async {
    await Share.shareXFiles([XFile.fromData(png, mimeType: 'image/png', name: 'salon-qr.png')], text: info.link);
  }

  /// Opens the system print / save / share sheet for the PDF. The poster is generated by the server.
  Future<void> _poster(SalonQrInfo info) async {
    setState(() => _busy = true);
    try {
      final pdf = await widget.api.poster(size: _size, theme: _theme);
      await Printing.layoutPdf(onLayout: (_) async => pdf, name: posterFileName(info.salonName, _size));
    } on ApiException catch (e) {
      _toast(e.message);
    } catch (_) {
      _toast('Could not open the poster. Please try again.');
    } finally {
      if (mounted) setState(() => _busy = false);
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(title: const Text('QR code and poster')),
      body: SafeArea(child: _body(context)),
    );
  }

  Widget _body(BuildContext context) {
    if (_loading) return const LoadingView(label: 'Preparing your QR code…');
    final info = _info;
    final png = _png;
    if (_error != null || info == null || png == null) {
      final e = _error;
      // 409 = the salon is not approved (or is suspended): the message from the server explains it.
      return e != null && e.statusCode == 409
          ? EmptyView(icon: Icons.qr_code_2, title: 'QR code not available yet', message: e.message)
          : ErrorView(message: e?.message ?? 'Could not load your QR code.', requestId: e?.requestId, onRetry: _load);
    }
    final text = Theme.of(context).textTheme;
    return ListView(padding: const EdgeInsets.all(AppSpacing.lg), children: [
      Center(
        child: Container(
          padding: const EdgeInsets.all(AppSpacing.md),
          decoration: BoxDecoration(color: Colors.white, borderRadius: BorderRadius.circular(AppRadius.card), border: Border.all(color: AppColors.border)),
          child: Image.memory(png, width: 240, height: 240, semanticLabel: 'QR code for ${info.salonName}', filterQuality: FilterQuality.none),
        ),
      ),
      const SizedBox(height: AppSpacing.md),
      Text('Scan to Book Your Appointment', textAlign: TextAlign.center, style: text.titleMedium),
      const SizedBox(height: AppSpacing.xs),
      Text('This code is permanent. It keeps working when you change your salon details.', textAlign: TextAlign.center, style: text.bodySmall),
      const SizedBox(height: AppSpacing.lg),
      Card(
        child: ListTile(
          title: SelectableText(info.link, maxLines: 2),
          subtitle: Text('Code ${info.code}'),
          trailing: IconButton(tooltip: 'Copy link', icon: const Icon(Icons.copy), onPressed: () => _copy(info.link)),
        ),
      ),
      const SizedBox(height: AppSpacing.sm),
      Row(children: [
        Expanded(child: OutlinedButton.icon(onPressed: () => _shareLink(info), icon: const Icon(Icons.share_outlined), label: const Text('Share link'))),
        const SizedBox(width: AppSpacing.sm),
        Expanded(child: OutlinedButton.icon(onPressed: () => _shareImage(info, png), icon: const Icon(Icons.image_outlined), label: const Text('Share QR image'))),
      ]),
      const SizedBox(height: AppSpacing.xl),
      Text('Printable poster', style: text.titleMedium),
      const SizedBox(height: AppSpacing.xs),
      Text('Salon name, QR code, instructions and address on one page. Print it, save it as a PDF or share it.', style: text.bodySmall),
      const SizedBox(height: AppSpacing.md),
      SegmentedButton<String>(
        segments: [for (final s in info.posterSizes) ButtonSegment<String>(value: s, label: Text(s))],
        selected: {_size},
        onSelectionChanged: _busy ? null : (v) => setState(() => _size = v.first),
      ),
      const SizedBox(height: AppSpacing.sm),
      SegmentedButton<String>(
        segments: [for (final t in info.posterThemes) ButtonSegment<String>(value: t, label: Text(t == 'dark' ? 'Dark (for screens)' : 'Light (for printing)'))],
        selected: {_theme},
        onSelectionChanged: _busy ? null : (v) => setState(() => _theme = v.first),
      ),
      const SizedBox(height: AppSpacing.md),
      FilledButton.icon(
        onPressed: _busy ? null : () => _poster(info),
        icon: _busy ? const SizedBox(width: 18, height: 18, child: CircularProgressIndicator(strokeWidth: 2)) : const Icon(Icons.print_outlined),
        label: Text(_busy ? 'Preparing…' : 'Print, save or share poster'),
      ),
      const SizedBox(height: AppSpacing.sm),
      Text('Posters show Latin letters only. Names in other scripts print as ? (the QR code is not affected).', style: text.bodySmall),
    ]);
  }
}
