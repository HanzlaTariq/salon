import { Transform, Type } from 'class-transformer';
import { ArrayMaxSize, ArrayMinSize, IsArray, IsBoolean, IsIn, IsISO8601, IsObject, IsOptional, IsUUID, ValidateNested } from 'class-validator';
import { SYNC_KINDS, SYNC_LIMITS, SyncKind } from '../sync.types';

/**
 * The ENVELOPE of one offline operation. A malformed envelope is a bug of the app and rejects the whole request (400); the PAYLOAD is
 * validated per kind by parsePayload(), so one bad operation never blocks the rest of the batch. The salon, the user and the staff
 * member are never accepted here: they come from the verified session.
 */
export class SyncOperationDto {
  /** Generated by the app (UUID). The same id sent again is the same operation: applied once, answered the same every time. */
  @IsUUID() operationId!: string;
  @IsIn(SYNC_KINDS as unknown as string[]) kind!: SyncKind;
  /** The device clock when the person acted. Bounded by the server (never in the future, never older than 48 hours). */
  @IsISO8601({ strict: true }) createdAt!: string;
  @IsOptional() @IsUUID() appointmentId?: string;
  /** Instead of appointmentId: the id of a WALK_IN_CREATE operation of this same user (the app does not know the server id yet). */
  @IsOptional() @IsUUID() refOperationId?: string;
  @IsOptional() @IsObject() payload?: Record<string, unknown>;
}

export class PushDto {
  /** Random id generated once per installation. Stored with every operation for diagnostics; never used for authorization. */
  @IsUUID() deviceId!: string;
  @IsArray() @ArrayMinSize(1) @ArrayMaxSize(SYNC_LIMITS.maxOperationsPerPush) @ValidateNested({ each: true }) @Type(() => SyncOperationDto)
  operations!: SyncOperationDto[];
}

export class PullQuery {
  /** The `serverTime` of the previous pull. Left out (or too old): a full snapshot of the window. */
  @IsOptional() @IsISO8601({ strict: true }) since?: string;
  /** The staff list, services and policy. Always included in a full snapshot; a delta pull only sends them when asked. */
  @IsOptional() @Transform(({ value }) => value === 'true' || value === true) @IsBoolean() catalog?: boolean;
}
