import { Injectable } from '@nestjs/common';
import { Tx } from '../salons/salons.repository';

/** All SQL for Phase 11. Every method runs inside a TenantDb transaction, so Row-Level Security applies. */
@Injectable()
export class QrRepository {
  async findBySalon(tx: Tx, salonId: string): Promise<{ code: string; createdAt: Date } | null> {
    const r = await tx.$queryRaw<Array<{ code: string; created_at: Date }>>`
      SELECT code, created_at FROM salon_qr_codes WHERE salon_id = ${salonId}::uuid`;
    return r[0] ? { code: r[0].code, createdAt: r[0].created_at } : null;
  }

  /** Creates the salon's code if it has none (the approval trigger normally did it already). The code is generated by the database. */
  async createIfMissing(tx: Tx, salonId: string): Promise<number> {
    return tx.$executeRaw`
      INSERT INTO salon_qr_codes (salon_id, code) VALUES (${salonId}::uuid, salon_qr_new_code()) ON CONFLICT (salon_id) DO NOTHING`;
  }

  /** Public read: visible only for APPROVED salons (policy public_read_approved). */
  async salonIdByCode(tx: Tx, code: string): Promise<string | null> {
    const r = await tx.$queryRaw<Array<{ salon_id: string }>>`SELECT salon_id FROM salon_qr_codes WHERE code = ${code}::varchar`;
    return r[0]?.salon_id ?? null;
  }
}
